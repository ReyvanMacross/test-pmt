-- 13. ROW LEVEL SECURITY (RLS) DASAR (Bisa diakses publik untuk read website aktif)
alter table public.templates enable row level security;
alter table public.websites enable row level security;
alter table public.menu_items enable row level security;
alter table public.contents enable row level security;
alter table public.news_items enable row level security;
alter table public.gallery_albums enable row level security;
alter table public.gallery_items enable row level security;
alter table public.wilayah_profiles enable row level security;

-- Policy: Publik boleh membaca website yang statusnya active
create policy "Allow public read active websites" on public.websites for select using (status = 'active');
create policy "Allow public read templates" on public.templates for select using (true);
create policy "Allow public read menu_items" on public.menu_items for select using (is_active = true);
create policy "Allow public read contents" on public.contents for select using (true);
create policy "Allow public read news_items" on public.news_items for select using (true);
create policy "Allow public read gallery_albums" on public.gallery_albums for select using (true);
create policy "Allow public read gallery_items" on public.gallery_items for select using (true);
create policy "Allow public read wilayah_profiles" on public.wilayah_profiles for select using (true);

-- Policy untuk authenticated users (Admin / User Login)
create policy "Allow authenticated full access to websites" on public.websites for all using (auth.role() = 'authenticated');
create policy "Allow authenticated full access to contents" on public.contents for all using (auth.role() = 'authenticated');
create policy "Allow authenticated full access to news_items" on public.news_items for all using (auth.role() = 'authenticated');
create policy "Allow authenticated full access to gallery_albums" on public.gallery_albums for all using (auth.role() = 'authenticated');
create policy "Allow authenticated full access to gallery_items" on public.gallery_items for all using (auth.role() = 'authenticated');
create policy "Allow authenticated full access to wilayah_profiles" on public.wilayah_profiles for all using (auth.role() = 'authenticated');
create policy "Allow authenticated full access to profiles" on public.profiles for all using (auth.role() = 'authenticated');
create policy "Allow public read profiles" on public.profiles for select using (true);
